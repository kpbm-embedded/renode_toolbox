/* WeAct MiniSTM32H743 bare-metal demo, run on a Renode platform generated from the board's
 * devicetree by dts2repl: USART1 banner and LED PE3 (active low). */
#include <stdint.h>
#include "bm.h"

#define RCC_AHB4ENR  REG32(0x580244E0)
#define RCC_APB2ENR  REG32(0x580244F0)
#define GPIOE_MODER  REG32(0x58021000)
#define GPIOE_BSRR   REG32(0x58021018)
#define USART1_CR1   REG32(0x40011000)
#define USART1_BRR   REG32(0x4001100C)
#define USART1_ISR   REG32(0x4001101C)
#define USART1_TDR   REG32(0x40011028)

void bm_putc(char c)
{
    while (!(USART1_ISR & (1u << 7))) /* TXE */
        ;
    USART1_TDR = (uint8_t)c;
}

int main(void)
{
    RCC_AHB4ENR |= 1u << 4;   /* GPIOE */
    RCC_APB2ENR |= 1u << 4;   /* USART1 */
    GPIOE_MODER = (GPIOE_MODER & ~(3u << 6)) | (1u << 6);
    USART1_BRR = 556;         /* 64 MHz HSI / 115200 */
    USART1_CR1 = (1u << 3) | 1u; /* TE | UE */
    bm_puts("Hello from WeAct STM32H743 (platform generated by dts2repl)\n");
    for (uint32_t n = 0; n < 6; n++) {
        int on = !(n & 1);
        GPIOE_BSRR = on ? (1u << (3 + 16)) : (1u << 3); /* active low */
        bm_puts(on ? "led on\n" : "led off\n");
        for (volatile uint32_t d = 0; d < 50000; d++)
            ;
    }
    bm_puts("done\n");
    for (;;)
        ;
}
